package com.ove.migration;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.UUID;

import org.hibernate.cfg.Configuration;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.testcontainers.postgresql.PostgreSQLContainer;

import com.ove.watchlist.domain.Watchlist;

class WatchlistUuidMigrationTest {
    private static final PostgreSQLContainer POSTGRES = new PostgreSQLContainer("postgres:16-alpine");

    @BeforeAll
    static void startDatabase() {
        POSTGRES.start();
    }

    @AfterAll
    static void stopDatabase() {
        POSTGRES.stop();
    }

    @Test
    void preservesRowsAndConstraintsAndCanRunAgain() throws Exception {
        try (Connection connection = connect(); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE watchlists (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "user_id uuid NOT NULL, symbol varchar(20) NOT NULL, added_at timestamptz NOT NULL, "
                    + "CONSTRAINT uk_watchlists_user_symbol UNIQUE (user_id, symbol))");
            UUID userId = UUID.randomUUID();
            statement.execute("INSERT INTO watchlists (user_id, symbol, added_at) VALUES ('" + userId
                    + "', 'KRW-BTC', '2026-10-28T00:00:00Z')");
            statement.execute(migration());
            UUID id;
            try (var rows = statement.executeQuery("SELECT * FROM watchlists")) {
                assertThat(rows.next()).isTrue();
                id = rows.getObject("id", UUID.class);
                assertThat(id).isNotNull();
                assertThat(rows.getObject("user_id", UUID.class)).isEqualTo(userId);
                assertThat(rows.getString("symbol")).isEqualTo("KRW-BTC");
                assertThat(rows.getTimestamp("added_at").toInstant().toString()).isEqualTo("2026-10-28T00:00:00Z");
                assertThat(rows.next()).isFalse();
            }
            statement.execute(migration());
            try (var rows = statement.executeQuery("SELECT id FROM watchlists")) {
                assertThat(rows.next()).isTrue();
                assertThat(rows.getObject(1, UUID.class)).isEqualTo(id);
            }
            verifyHibernateMapping(id, userId);
            statement.execute("INSERT INTO watchlists VALUES (gen_random_uuid(), '" + userId
                    + "', 'KRW-ETH', CURRENT_TIMESTAMP)");
            assertThatThrownBy(() -> statement.execute("INSERT INTO watchlists VALUES (gen_random_uuid(), '"
                    + userId + "', 'KRW-BTC', CURRENT_TIMESTAMP)"))
                    .isInstanceOf(SQLException.class);
            statement.execute("DROP TABLE watchlists");
        }
    }

    @Test
    void refusesConversionWhenOtherTablesReferenceIds() throws Exception {
        try (Connection connection = connect(); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE watchlists (id bigint PRIMARY KEY)");
            statement.execute("CREATE TABLE watchlist_refs (id bigint REFERENCES watchlists(id))");
            assertThatThrownBy(() -> statement.execute(migration())).isInstanceOf(SQLException.class);
            statement.execute("ROLLBACK");
            try (var rows = statement.executeQuery("SELECT data_type FROM information_schema.columns "
                    + "WHERE table_name = 'watchlists' AND column_name = 'id'")) {
                assertThat(rows.next()).isTrue();
                assertThat(rows.getString(1)).isEqualTo("bigint");
            }
            statement.execute("DROP TABLE watchlist_refs, watchlists");
        }
    }

    private void verifyHibernateMapping(UUID existingId, UUID userId) {
        Configuration configuration = new Configuration()
                .addAnnotatedClass(Watchlist.class)
                .setProperty("hibernate.connection.url", POSTGRES.getJdbcUrl())
                .setProperty("hibernate.connection.username", POSTGRES.getUsername())
                .setProperty("hibernate.connection.password", POSTGRES.getPassword())
                .setProperty("hibernate.hbm2ddl.auto", "validate")
                .setProperty("hibernate.physical_naming_strategy",
                        "org.hibernate.boot.model.naming.PhysicalNamingStrategySnakeCaseImpl");
        try (var factory = configuration.buildSessionFactory(); var session = factory.openSession()) {
            assertThat(session.find(Watchlist.class, existingId).getSymbol()).isEqualTo("KRW-BTC");
            var transaction = session.beginTransaction();
            Watchlist added = Watchlist.builder().userId(userId).symbol("KRW-XRP").build();
            session.persist(added);
            session.flush();
            UUID generatedId = added.getId();
            assertThat(generatedId).isNotNull();
            transaction.commit();
            session.clear();
            assertThat(session.find(Watchlist.class, generatedId).getSymbol()).isEqualTo("KRW-XRP");
        }
    }

    private Connection connect() throws SQLException {
        return DriverManager.getConnection(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
    }

    private String migration() throws Exception {
        return Files.readString(Path.of("docs/sql/watchlist-id-to-uuid.sql"));
    }
}
